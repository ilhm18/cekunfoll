import JSZip from 'jszip';
import { InstagramUser, AnalysisResult } from '../types';

/**
 * Normalizes username string
 */
export function cleanUsername(raw: string): string {
  if (!raw) return '';
  let cleaned = raw.trim();
  // Strip url parts if full url was passed
  if (cleaned.includes('instagram.com/')) {
    const parts = cleaned.split('instagram.com/');
    cleaned = parts[1] || '';
    cleaned = cleaned.replace(/^_u\//, '');
    cleaned = cleaned.split('/')[0].split('?')[0];
  }
  // Remove @ prefix and trim
  cleaned = cleaned.replace(/^@+/, '').trim().toLowerCase();
  // Remove trailing slashes or query parameters
  cleaned = cleaned.split('/')[0].split('?')[0].split('#')[0];
  return cleaned;
}

const INVALID_USERNAMES = new Set([
  'instagram',
  'help',
  'about',
  'explore',
  'direct',
  'stories',
  'reels',
  'p',
  'legal',
  'privacy',
  'terms',
]);

/**
 * Detects deleted/ghost/placeholder accounts generated by Meta/Instagram
 * such as __deleted__bhiebea..., deleted_*, instagram_user*, etc.
 */
export function isDeletedOrGhostAccount(rawUsername: string): boolean {
  if (!rawUsername) return true;
  const lower = rawUsername.toLowerCase().trim().replace(/^@+/, '');

  // 1. Any username containing 'deleted' (like __deleted__*, _deleted_*, deleted_*)
  if (lower.includes('deleted')) {
    return true;
  }

  // 2. Ghost or placeholder prefixes from Meta exports
  if (
    lower.startsWith('instagram_user') ||
    lower.startsWith('facebook_user') ||
    lower.startsWith('meta_user') ||
    lower.startsWith('user_not_found') ||
    lower.startsWith('page_not_found') ||
    lower.startsWith('unknown_user') ||
    lower.startsWith('ghost_') ||
    lower.startsWith('inactive_') ||
    lower === 'null' ||
    lower === 'undefined' ||
    lower === 'instagram'
  ) {
    return true;
  }

  // 3. Pure numeric IDs (e.g. 1000847291247) which Meta leaves when handle is deleted
  if (/^\d{5,}$/.test(lower)) {
    return true;
  }

  // 4. Double underscores at start/end (typical for internal Meta deleted hash usernames)
  if (lower.startsWith('__') || lower.endsWith('__')) {
    return true;
  }

  return false;
}

/**
 * Parses Instagram HTML string for accounts
 */
export function parseInstagramHTML(htmlText: string): InstagramUser[] {
  const parser = new DOMParser();
  const doc = parser.parseFromString(htmlText, 'text/html');
  const links = Array.from(doc.querySelectorAll('a'));
  const usersMap = new Map<string, InstagramUser>();

  for (const link of links) {
    const href = link.getAttribute('href') || '';
    let username = '';

    // Prefer username extracted from official Instagram profile link
    if (href.includes('instagram.com/')) {
      const fromHref = cleanUsername(href);
      if (fromHref && !INVALID_USERNAMES.has(fromHref) && !fromHref.includes(' ')) {
        username = fromHref;
      }
    }

    // Fallback to textContent if not found in href
    if (!username) {
      const textCandidate = cleanUsername(link.textContent?.trim() || '');
      if (textCandidate && !INVALID_USERNAMES.has(textCandidate) && !textCandidate.includes(' ')) {
        username = textCandidate;
      }
    }

    if (!username || isDeletedOrGhostAccount(username)) continue;

    // Try finding timestamp in sibling or parent node
    let timestamp: number | undefined;
    let dateStr: string | undefined;

    const parent = link.closest('div');
    if (parent) {
      const divs = Array.from(parent.querySelectorAll('div'));
      for (const d of divs) {
        const text = d.textContent?.trim() || '';
        const parsedDate = Date.parse(text);
        if (!isNaN(parsedDate) && text.length > 5 && /\d{4}/.test(text)) {
          timestamp = Math.floor(parsedDate / 1000);
          dateStr = new Date(parsedDate).toLocaleDateString('id-ID', {
            day: 'numeric',
            month: 'short',
            year: 'numeric',
          });
          break;
        }
      }
    }

    if (!usersMap.has(username)) {
      usersMap.set(username, {
        username,
        href: `https://www.instagram.com/${username}/`,
        timestamp,
        dateStr,
      });
    }
  }

  return Array.from(usersMap.values());
}

/**
 * Parses Instagram JSON content
 */
export function parseInstagramJSON(jsonContent: any): InstagramUser[] {
  const usersMap = new Map<string, InstagramUser>();

  function extractFromArray(arr: any[]) {
    for (const item of arr) {
      if (!item) continue;

      if (item.string_list_data && Array.isArray(item.string_list_data)) {
        for (const sld of item.string_list_data) {
          const rawVal = sld.value || sld.href || item.title || '';
          const username = cleanUsername(rawVal);
          if (username && !INVALID_USERNAMES.has(username) && !isDeletedOrGhostAccount(username)) {
            const timestamp = sld.timestamp ? Number(sld.timestamp) : undefined;
            const dateStr = timestamp
              ? new Date(timestamp * 1000).toLocaleDateString('id-ID', {
                  day: 'numeric',
                  month: 'short',
                  year: 'numeric',
                })
              : undefined;

            if (!usersMap.has(username)) {
              usersMap.set(username, {
                username,
                href: sld.href || `https://www.instagram.com/${username}/`,
                timestamp,
                dateStr,
              });
            }
          }
        }
      } else if (typeof item === 'string') {
        const username = cleanUsername(item);
        if (username && !INVALID_USERNAMES.has(username) && !isDeletedOrGhostAccount(username) && !usersMap.has(username)) {
          usersMap.set(username, {
            username,
            href: `https://www.instagram.com/${username}/`,
          });
        }
      } else if (item.value || item.title) {
        const username = cleanUsername(item.value || item.title);
        if (username && !INVALID_USERNAMES.has(username) && !isDeletedOrGhostAccount(username) && !usersMap.has(username)) {
          usersMap.set(username, {
            username,
            href: `https://www.instagram.com/${username}/`,
          });
        }
      }
    }
  }

  if (Array.isArray(jsonContent)) {
    extractFromArray(jsonContent);
  } else if (typeof jsonContent === 'object' && jsonContent !== null) {
    if (Array.isArray(jsonContent.relationships_following)) {
      extractFromArray(jsonContent.relationships_following);
    } else if (Array.isArray(jsonContent.relationships_followers)) {
      extractFromArray(jsonContent.relationships_followers);
    } else {
      for (const key of Object.keys(jsonContent)) {
        if (Array.isArray(jsonContent[key])) {
          extractFromArray(jsonContent[key]);
        }
      }
    }
  }

  return Array.from(usersMap.values());
}

/**
 * Parses raw text input
 */
export function parseRawUsernameList(text: string): InstagramUser[] {
  const lines = text.split(/[\r\n,;\t]+/);
  const usersMap = new Map<string, InstagramUser>();

  for (const raw of lines) {
    const username = cleanUsername(raw);
    if (username && !INVALID_USERNAMES.has(username) && !isDeletedOrGhostAccount(username) && !usersMap.has(username)) {
      usersMap.set(username, {
        username,
        href: `https://www.instagram.com/${username}/`,
      });
    }
  }

  return Array.from(usersMap.values());
}

export interface DeactivationCheck {
  isDeactivated: boolean;
  reason?: string;
}

/**
 * Checks if an account looks deactivated, deleted, or missing
 */
export function checkDeactivatedStatus(username: string): DeactivationCheck {
  if (!username) {
    return { isDeactivated: true, reason: 'Akun Kosong / Tidak Ada' };
  }
  if (isDeletedOrGhostAccount(username)) {
    return { isDeactivated: true, reason: 'Akun Terhapus Meta' };
  }
  const lower = username.toLowerCase();

  // Pure numeric IDs
  if (/^\d{5,}$/.test(lower)) {
    return { isDeactivated: true, reason: 'ID Numerik Meta' };
  }

  // Instagram username format violation
  if (lower.length > 30 || lower.length < 1) {
    return { isDeactivated: true, reason: 'Panjang Username Tidak Sesuai' };
  }
  if (!/^[a-z0-9._]+$/.test(lower)) {
    return { isDeactivated: true, reason: 'Karakter Tidak Dikenal' };
  }
  if (lower.startsWith('.') || lower.endsWith('.') || lower.includes('..')) {
    return { isDeactivated: true, reason: 'Format Handle Tidak Valid' };
  }

  return { isDeactivated: false };
}

export function isDeactivatedUsername(username: string): boolean {
  return checkDeactivatedStatus(username).isDeactivated;
}

/**
 * Computes difference and categorization between following and followers
 */
export function computeAnalysis(
  following: InstagramUser[],
  followers: InstagramUser[],
  sourceType: AnalysisResult['sourceType'] = 'html'
): AnalysisResult {
  // Strictly filter out any deleted / placeholder accounts (like __deleted__*, instagram_user*, etc.)
  const cleanFollowing = following.filter(
    (u) => u.username && !isDeletedOrGhostAccount(u.username)
  );
  const cleanFollowers = followers.filter(
    (u) => u.username && !isDeletedOrGhostAccount(u.username)
  );

  const followersSet = new Set(cleanFollowers.map((u) => u.username.toLowerCase()));
  const followingSet = new Set(cleanFollowing.map((u) => u.username.toLowerCase()));

  // Not following back = in following, but NOT in followers
  const notFollowingBack = cleanFollowing.filter(
    (user) => !followersSet.has(user.username.toLowerCase())
  );

  // Fans = in followers, but NOT in following
  const fans = cleanFollowers.filter(
    (user) => !followingSet.has(user.username.toLowerCase())
  );

  // Mutual = both follow each other
  const mutual = cleanFollowing.filter((user) =>
    followersSet.has(user.username.toLowerCase())
  );

  return {
    following: cleanFollowing,
    followers: cleanFollowers,
    notFollowingBack,
    fans,
    mutual,
    deactivated: [],
    sourceType,
    exportDate: new Date().toLocaleDateString('id-ID', {
      day: 'numeric',
      month: 'long',
      year: 'numeric',
    }),
  };
}

/**
 * Swaps following and followers in case they were uploaded in inverted order
 */
export function swapAnalysis(data: AnalysisResult): AnalysisResult {
  return computeAnalysis(data.followers, data.following, data.sourceType);
}

export interface AnalysisProgressStep {
  step: number;
  totalSteps: number;
  message: string;
  subMessage?: string;
  percent: number;
  followingCount?: number;
  followersCount?: number;
  deactivatedCount?: number;
}

/**
 * Unzips an Instagram data export ZIP and extracts followers & following with progress reporting
 */
export async function parseInstagramZip(
  zipFile: File,
  onProgress?: (progress: AnalysisProgressStep) => void
): Promise<AnalysisResult> {
  onProgress?.({
    step: 1,
    totalSteps: 4,
    message: 'Membuka dan membaca berkas ZIP...',
    subMessage: zipFile.name,
    percent: 15,
  });

  // Short pause to allow UI update
  await new Promise((r) => setTimeout(r, 200));

  const jszip = new JSZip();
  const zip = await jszip.loadAsync(zipFile);

  const followingUsersMap = new Map<string, InstagramUser>();
  const followersUsersMap = new Map<string, InstagramUser>();

  const filePaths = Object.keys(zip.files);

  onProgress?.({
    step: 2,
    totalSteps: 4,
    message: 'Mengekstrak data Following & Followers...',
    subMessage: 'Mencari berkas following.html dan followers_1.html...',
    percent: 45,
  });

  await new Promise((r) => setTimeout(r, 200));

  for (const path of filePaths) {
    const entry = zip.files[path];
    if (entry.dir) continue;

    // Look ONLY at the filename itself
    const filename = path.split('/').pop()?.toLowerCase() || '';

    if (!filename.endsWith('.html') && !filename.endsWith('.json') && !filename.endsWith('.htm')) {
      continue;
    }

    // Following files: "following.html", "following.json", "following_1.html", etc.
    const isFollowing = filename.startsWith('following') && !filename.includes('follower');

    // Followers files: "followers_1.html", "followers.html", "followers_1.json", etc.
    const isFollowers = filename.startsWith('follower') && !filename.startsWith('following');

    if (isFollowing) {
      const content = await entry.async('string');
      let parsed: InstagramUser[] = [];
      if (filename.endsWith('.json')) {
        try {
          parsed = parseInstagramJSON(JSON.parse(content));
        } catch {
          // ignore
        }
      } else {
        parsed = parseInstagramHTML(content);
      }
      for (const u of parsed) {
        followingUsersMap.set(u.username, u);
      }
    } else if (isFollowers) {
      const content = await entry.async('string');
      let parsed: InstagramUser[] = [];
      if (filename.endsWith('.json')) {
        try {
          parsed = parseInstagramJSON(JSON.parse(content));
        } catch {
          // ignore
        }
      } else {
        parsed = parseInstagramHTML(content);
      }
      for (const u of parsed) {
        followersUsersMap.set(u.username, u);
      }
    }
  }

  const followingUsers = Array.from(followingUsersMap.values()).filter(
    (u) => !isDeletedOrGhostAccount(u.username)
  );
  const followersUsers = Array.from(followersUsersMap.values()).filter(
    (u) => !isDeletedOrGhostAccount(u.username)
  );

  if (followingUsers.length === 0 && followersUsers.length === 0) {
    throw new Error(
      'Tidak ditemukan data followers atau following di dalam file ZIP. Pastikan saat download data dari Instagram, kamu mencentang "Pengikut dan yang diikuti".'
    );
  }

  // Pre-scan deactivated
  const detectedDeactivated = followingUsers.filter((u) => isDeactivatedUsername(u.username));

  onProgress?.({
    step: 3,
    totalSteps: 4,
    message: 'Menganalisis perbandingan akun...',
    subMessage: `Memeriksa ${followingUsers.length} following & ${followersUsers.length} followers...`,
    percent: 75,
    followingCount: followingUsers.length,
    followersCount: followersUsers.length,
  });

  await new Promise((r) => setTimeout(r, 300));

  onProgress?.({
    step: 4,
    totalSteps: 4,
    message: 'Menyusun daftar yang tidak mengikuti kembali...',
    subMessage: 'Memproses hasil analisis...',
    percent: 95,
    followingCount: followingUsers.length,
    followersCount: followersUsers.length,
  });

  await new Promise((r) => setTimeout(r, 250));

  return computeAnalysis(followingUsers, followersUsers, 'zip');
}
